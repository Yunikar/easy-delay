# Easy Delay - installer
# Copies EasyDelay.vst3 into the system VST3 folder and registers an
# uninstaller entry so it can be removed cleanly from Windows Settings.
# Requires administrator rights; the .cmd wrapper asks for elevation first.

$ErrorActionPreference = 'Stop'

$AppName     = 'Easy Delay'
$AppVersion  = '1.0.0'
$Publisher   = 'YangAudio'
$PluginDir   = Join-Path $PSScriptRoot 'EasyDelay.vst3'
$Vst3Root    = Join-Path $env:ProgramFiles 'Common Files\VST3'
$TargetDir   = Join-Path $Vst3Root 'EasyDelay.vst3'
$Uninstaller = Join-Path $TargetDir 'uninstall.ps1'
$InstallKey  = 'HKLM:\SOFTWARE\Microsoft\Windows\CurrentVersion\Uninstall\EasyDelay'

function Fail([string]$message)
{
    Write-Host ''
    Write-Host "Install failed: $message" -ForegroundColor Red
    exit 1
}

$isAdmin = ([Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole(
    [Security.Principal.WindowsBuiltInRole]::Administrator)

if (-not $isAdmin)
{
    Fail 'administrator rights are required. Right-click install.cmd and choose "Run as administrator".'
}

if (-not (Test-Path $PluginDir))
{
    Fail 'EasyDelay.vst3 is missing; unzip the whole package first.'
}

if (-not (Test-Path $Vst3Root))
{
    New-Item -ItemType Directory -Path $Vst3Root -Force | Out-Null
}

Write-Host "Installing to: $TargetDir"

if (Test-Path $TargetDir)
{
    Remove-Item -Path $TargetDir -Recurse -Force
}

Copy-Item -Path $PluginDir -Destination $TargetDir -Recurse -Force

$uninstallLines = @(
    '# Easy Delay - uninstaller (generated by the installer)'
    '$ErrorActionPreference = ''SilentlyContinue'''
    '$dir = Join-Path $env:ProgramFiles ''Common Files\VST3\EasyDelay.vst3'''
    'if (Test-Path $dir) { Remove-Item -Path $dir -Recurse -Force }'
    'Remove-Item -Path ''HKLM:\SOFTWARE\Microsoft\Windows\CurrentVersion\Uninstall\EasyDelay'' -Recurse -Force'
    'Write-Host ''Easy Delay uninstalled.'''
    'Start-Sleep -Seconds 2'
)
Set-Content -Path $Uninstaller -Value ($uninstallLines -join [Environment]::NewLine) -Encoding UTF8

$uninstallCommand = 'powershell.exe -NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File "' + $Uninstaller + '"'

if (-not (Test-Path $InstallKey))
{
    New-Item -Path $InstallKey -Force | Out-Null
}

Set-ItemProperty -Path $InstallKey -Name 'DisplayName'       -Value $AppName
Set-ItemProperty -Path $InstallKey -Name 'DisplayVersion'    -Value $AppVersion
Set-ItemProperty -Path $InstallKey -Name 'Publisher'         -Value $Publisher
Set-ItemProperty -Path $InstallKey -Name 'InstallLocation'   -Value $TargetDir
Set-ItemProperty -Path $InstallKey -Name 'UninstallString'   -Value $uninstallCommand
Set-ItemProperty -Path $InstallKey -Name 'QuietUninstallString' -Value $uninstallCommand
Set-ItemProperty -Path $InstallKey -Name 'DisplayIcon'       -Value (Join-Path $TargetDir 'Contents\x86_64-win\EasyDelay.vst3')

Write-Host ''
Write-Host 'Done. Rescan VST3 plugins in Studio One to see Easy Delay.' -ForegroundColor Green
Write-Host 'Uninstall from Windows Settings > Apps, or run the generated uninstall.ps1.'
Start-Sleep -Seconds 2
